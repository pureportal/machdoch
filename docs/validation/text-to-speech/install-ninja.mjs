import { mkdir, writeFile, readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
const root = "D:/Models/machdoch/speech/verification/ninja-1.13.2";
const response = await fetch("https://api.github.com/repos/ninja-build/ninja/releases/tags/v1.13.2", { headers: { "User-Agent": "machdoch-speech-verification" } });
if (!response.ok) throw new Error(`Ninja release metadata failed: ${response.status}`);
const release = await response.json();
const asset = release.assets.find(asset => asset.name === "ninja-win.zip");
if (!asset?.digest?.startsWith("sha256:")) throw new Error("The Ninja release has no published SHA-256 digest.");
const download = await fetch(asset.browser_download_url);
if (!download.ok) throw new Error(`Ninja download failed: ${download.status}`);
const bytes = Buffer.from(await download.arrayBuffer());
if (bytes.length > 10 * 1024 * 1024 || `sha256:${createHash("sha256").update(bytes).digest("hex")}` !== asset.digest) throw new Error("Ninja package integrity failed.");
await mkdir(root, { recursive: true });
const archive = `${root}/ninja-win.zip`;
await writeFile(archive, bytes);
const script = new URL("./install-encoder.ps1", import.meta.url).pathname.replace(/^\/([A-Z]:)/u, "$1");
execFileSync("C:/Windows/System32/WindowsPowerShell/v1.0/powershell.exe", ["-NoProfile", "-NonInteractive", "-File", script, "-Archive", archive, "-Destination", `${root}/bin`], { stdio: "inherit", windowsHide: true });
console.log(execFileSync(`${root}/bin/ninja.exe`, ["--version"], { encoding: "utf8", windowsHide: true }).trim());
await writeFile(`${root}/provenance.json`, JSON.stringify({ version: release.tag_name, source: asset.browser_download_url, digest: asset.digest }));
